/**
 * Flashcard data for the AIL training program.
 *
 * Card types follow Thalheimer's retrieval practice design:
 * - conceptual: Conceptual discrimination — "what is X vs Y?" (~30%)
 * - scenario: Scenario judgment — "what would you do?" (~30%)
 * - factual: Factual recall — "what is X?" (~25%)
 * - elaborative: Elaborative "why" — "why does X matter?" (~15%)
 *
 * Each card is tagged with the maximum module required to have learned
 * the concept (maxModule). Cards with maxModule: 0 cover program overview,
 * maxModule: 1 covers Module 1 content, etc.
 */

